"""Free sample responses for every priced route on this stall.

Static committed data under app/data/samples/ (+ the provenance manifest
at app/data/samples-manifest.json), generated by the fleet generator
(stall-row/scripts/gen_samples.py) from this service's recorded state
and its documented discovery examples. Served verbatim — no live
computation. Every body carries the in-band sample marker
(sample=true, live=false, source=recorded|schema-example, target,
recorded_at) so a sample is never mistaken for live data.
"""

from __future__ import annotations

import json
import os

_DATA = os.path.join(os.path.dirname(__file__), "data")
_SAMPLES_DIR = os.path.join(_DATA, "samples")
_MANIFEST = os.path.join(_DATA, "samples-manifest.json")


def _manifest() -> dict:
    with open(_MANIFEST, encoding="utf-8") as f:
        return json.load(f)


def index() -> dict:
    m = _manifest()
    return {
        "service": m["service"],
        "sample": True,
        "live": False,
        "note": (
            "Free sample responses, one per priced route. source=recorded "
            "is a real recorded response; source=schema-example shows the "
            "exact output shape only and is not a recorded result."
        ),
        "count": len(m["samples"]),
        "samples": [
            {
                "route": s["route"],
                "sample_url": f"/sample/{s['slug']}",
                "source": s["source"],
                "target": s["target"],
                "recorded_at": s["recorded_at"],
            }
            for s in m["samples"]
        ],
    }


def get(slug: str) -> dict | None:
    m = _manifest()
    if slug not in {s["slug"] for s in m["samples"]}:
        return None
    path = os.path.join(_SAMPLES_DIR, f"{slug}.json")
    try:
        with open(path, encoding="utf-8") as f:
            return json.load(f)
    except OSError:
        return None
