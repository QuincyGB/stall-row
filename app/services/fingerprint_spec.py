def _challenge(schema=None, description="A target service.", amount="20000"):
    challenge = {
        "x402Version": 2,
        "error": "Payment required",
        "resource": {
            "url": "https://example.com/v1/verdict",
            "description": description,
            "mimeType": "application/json",
        },
        "accepts": [
            {
                "scheme": "exact",
                "network": "eip155:8453",
                "asset": _USDC,
                "amount": amount,
                "payTo": _OWNER,
                "maxTimeoutSeconds": 300,
            }
        ],
    }
    if schema is not None:
        challenge["extensions"] = {
            "bazaar": {
                "info": {
                    "input": {
                        "type": "http",
                        "method": "POST",
                        "bodyType": "json",
                        "body": {},
                    },
                    "output": {"type": "json", "schema": schema},
                }
            }
        }
    return challenge


