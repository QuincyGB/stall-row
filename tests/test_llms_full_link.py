"""llms-full.txt (Item 7): the long-form companion to llms.txt is
committed at app/data/llms-full.txt (generated by the fleet's
llms_full.py from route_registry.json), served verbatim at
GET /llms-full.txt, and linked from llms.txt + skill.md. The
committed file must name every priced route at its manifest price
and carry the worked example pair per route.
"""

import json
from pathlib import Path

from fastapi.testclient import TestClient

import app.main as main
from app.config import load_settings
from app.discovery import LLMS_FULL_PATH, llms_txt, skill_md, x402_manifest

BASE = "https://verdictrow.example"
DATA = Path(__file__).resolve().parent.parent / "app" / "data"


def _priced():
    manifest = x402_manifest(load_settings(), BASE)
    return [r for r in manifest["resources"] if r.get("method") == "POST"]


def _committed() -> str:
    return (DATA / "llms-full.txt").read_text()


def test_llms_full_path_constant():
    assert LLMS_FULL_PATH == "/llms-full.txt"


def test_skill_and_llms_link_llms_full():
    settings = load_settings()
    for doc in (skill_md(settings, BASE), llms_txt(settings, BASE)):
        assert BASE + "/llms-full.txt" in doc


def test_committed_llms_full_covers_the_priced_routes():
    text = _committed()
    priced = _priced()
    assert "patrol@verdictrow.com" in text
    for r in priced:
        # The committed file is generated against the stall's real
        # origin, not this test's example base: assert on the path.
        path = "/" + r["resource"].split("/", 3)[-1]
        assert path in text, r["resource"]
        assert r["price"] in text, r["resource"]
    assert text.count("Worked request example (fixture)") == len(priced)
    assert text.count("Worked response example (fixture)") == len(priced)
    for section in ("## Pack mechanics", "## Recheck feed v2",
                    "## Watch, webhooks and corrections policy",
                    "## MCP + SDK pointers"):
        assert section in text, section


def test_llms_full_served_verbatim():
    with TestClient(main.app) as client:
        r = client.get("/llms-full.txt")
        assert r.status_code == 200
        assert r.text == _committed()
        for surface in ("/llms.txt", "/skill.md"):
            doc = client.get(surface)
            assert doc.status_code == 200
            assert "/llms-full.txt" in doc.text
