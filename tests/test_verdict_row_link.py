"""The Fleet Discovery Bundle + A2A card links: every discovery
surface names this stall's /.well-known/verdict-row.json bundle and
/.well-known/a2a-agent-card.json (committed at app/data/, served
verbatim, generated by the fleet's discovery_bundle.py).
"""

import json
from pathlib import Path

from app.config import load_settings
from app.discovery import (
    A2A_AGENT_CARD_PATH,
    VERDICT_ROW_BUNDLE_PATH,
    agent_card,
    llms_txt,
    skill_md,
    verdict_row_extension,
    x402_manifest,
)

BASE = "https://verdictrow.example"
BUNDLE = BASE + "/.well-known/verdict-row.json"
A2A = BASE + "/.well-known/a2a-agent-card.json"
DATA = Path(__file__).resolve().parent.parent / "app" / "data"


def test_verdict_row_paths_and_extension():
    assert VERDICT_ROW_BUNDLE_PATH == "/.well-known/verdict-row.json"
    assert A2A_AGENT_CARD_PATH == "/.well-known/a2a-agent-card.json"
    ext = verdict_row_extension(BASE)
    assert ext["bundle"] == BUNDLE
    assert ext["a2a_agent_card"] == A2A


def test_manifest_and_card_link_the_bundle_and_a2a_card():
    settings = load_settings()
    manifest = x402_manifest(settings, BASE)
    assert manifest["extensions"]["verdict_row"]["bundle"] == BUNDLE
    assert manifest["extensions"]["verdict_row"]["a2a_agent_card"] == A2A
    card = agent_card(settings, BASE)
    assert card["verdict_row"]["bundle"] == BUNDLE
    assert card["verdict_row"]["a2a_agent_card"] == A2A


def test_skill_and_llms_name_the_bundle_and_a2a_card():
    settings = load_settings()
    for doc in (skill_md(settings, BASE), llms_txt(settings, BASE)):
        assert BUNDLE in doc
        assert A2A in doc


def test_committed_bundle_lists_the_whole_fleet():
    bundle = json.loads((DATA / "verdict-row.json").read_text())
    assert bundle["kind"] == "verdict-row-discovery-bundle/v1"
    assert bundle["fleet"]["stall_count"] == 5
    assert bundle["fleet"]["priced_route_count"] == 40
    assert len(bundle["stalls"]) == 5
    assert bundle["signature"].startswith("0x")
    assert bundle["signer"].startswith("0x")


def test_committed_a2a_card_mirrors_the_priced_routes():
    settings = load_settings()
    manifest = x402_manifest(settings, BASE)
    priced = [r for r in manifest["resources"] if r.get("method") == "POST"]
    card = json.loads((DATA / "a2a-agent-card.json").read_text())
    assert card["protocolVersion"] == "0.3.0"
    assert card["contactEmail"] == "patrol@verdictrow.com"
    assert len(card["skills"]) == len(priced)
    by_id = {s["id"]: s for s in card["skills"]}
    for r in priced:
        path = r["resource"].split("/", 3)[-1]
        sid = path.replace("/", "-")
        assert sid in by_id, sid
        base_accept = next(a for a in r["accepts"]
                           if a["network"] == "eip155:8453")
        assert by_id[sid]["price"]["amount_units"] == base_accept["amount"]
        assert by_id[sid]["url"].endswith("/" + path)
